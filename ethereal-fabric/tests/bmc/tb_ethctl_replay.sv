// Module:      tb_ethctl_replay (testbench, self-checking)
// Description: E1-RUN3 CAPSTONE — an ethctl-GENERATED EFP session script
//              (ethereal.efp-session.v0 JSON, emitted by
//              `ethctl run/stop --transport efp --emit-session`, see
//              ethereal-tools/tools/efp_client.py) replays against the REAL
//              daemon RTL chain, with the host BFM as the SECOND AXI master:
//
//                host BFM --AXI4--+
//                                 v
//                NEORV32 --XBUS--> eth_wb2axi --> eth_axi_xbar (2 masters)
//                                                    | 1 slave (512 B window)
//                                           emri_axi_adapter --> emri_regfile
//                                                    | OCC master
//                                              occ_top --fbus--> fabric_top (2x2 CLB)
//                                                            +-> column_cfg_ram
//
//              Same wiring as tb_bmc_daemon, but the host side is NOT a
//              hand-written scenario: it is a line-based replayer for the
//              machine-generated session JSON. Each op line is a compact
//              one-line JSON object keyed by the literal `{"op":"` marker;
//              all 32-bit values are "0x........" hex strings (token scan):
//                {"op":"write","addr":"0x18","data":"0x........"}
//                {"op":"read","addr":"0x16","mask":"0x3f","value":"0x26"}
//                {"op":"poll","addr":"0x16","mask":"0x10","value":"0x00"}
//                {"op":"stream","addr":"0x09","count":12,"words":["0x..",..]}
//              read/poll masks make the session self-checking; stream writes
//              each word to OCC_WDATA while the daemon is in LOAD.
//
//              Scenario (spec emri-v0.md sec 3.2):
//                1. replay session_run_a.json  (ethctl run  --region auto)
//                   -> RUNNING r0, clb_out_obs[0] toggles (TFF, real fabric)
//                2. replay session_stop_a.json (ethctl stop --region 0)
//                   -> STOPPED, clb_out_obs[0] constant 0 (region blanked)
//
//              The .eth under test is packed+signed by ethimg with the SAME
//              fixed-seed Ed25519 key as the daemon keyring.h
//              (gen_daemon_vectors.KEY_SEED), regenerated by the Makefile
//              test-sv step via `efp_client.py --emit-demo generated/ethctl`.
//              The daemon UART log is SPOT-CHECKED (substring containment of
//              the key lines: boot banner / selftest / verify ok / RUNNING /
//              STOPPED), not exact-matched — the session is machine-generated.
//
//              Frame format: v0 cfg-addr-addressed (the format the v0.2 daemon
//              consumes); the bit-packed frame_decoder path is covered by
//              tb_bmc_axi_fabric. Region 0 frame base = 0x0000.
// Maintainer:  BaiTian6641
// Created:     2026-09-01
// Tags:        TESTBENCH
// Plan-Ref:    ethereal-spec/control/emri-v0.md §3.2 (EFP command block);
//              ethereal-plan/subsystems/S08-运行时daemon与ethctl.md (E1-RUN3)
// Notes:       Verilator --binary --timing (same ADR-018 §7.5 cycle-count
//              exemption as tb_bmc_daemon: ~83M cycles per Ed25519 verify on
//              the iterative-mul NEORV32 netlist; boot selftest dominates).
//              UART bit time = 2 clk (NEORV32 reset defaults PRSC=0/BAUD=0).
