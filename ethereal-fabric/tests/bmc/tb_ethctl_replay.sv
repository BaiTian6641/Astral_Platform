  // ============================================================================
  // Concurrent UART 8N1 receiver (idle-high, start bit low, LSB first)
  // ============================================================================
  localparam int MAXB = 8192;
  bit [7:0] rxq [0:MAXB-1];
  integer   rxn = 0;   // received count

  always @(negedge uart0_txd) begin : uart_rx
      integer i;
      logic [7:0] b;
      #(BIT_NS / 2);
      if (uart0_txd === 1'b0) begin
          b = 8'h00;
          for (i = 0; i < 8; i = i + 1) begin
              #(BIT_NS);
              b[i] = uart0_txd;
          end
          #(BIT_NS);
          if (uart0_txd === 1'b1 && rxn < MAXB) begin
              rxq[rxn] = b;
              rxn = rxn + 1;
          end
      end
  end

  // ============================================================================
  // Check helpers
  // ============================================================================
  integer errors = 0;
  task automatic chk(input logic cond, input string msg);
      begin
          if (cond) $display("  ok: %0s", msg);
          else begin
              errors = errors + 1;
              $display("  FAIL: %0s", msg);
          end
      end
  endtask

  // Spot-check: block (bounded) until the daemon UART log CONTAINS string s.
  // (Containment, not exact-match: the session is machine-generated, so the
  // TB checks the key daemon lines only.)
  task automatic wait_uart_contains(input string s, input string tag);
      integer to, base, j;
      logic found, m;
      begin
          to = 0;
          found = 1'b0;
          while (!found && to < 4000000) begin
              for (base = 0; base + s.len() <= rxn; base = base + 1) begin
                  m = 1'b1;
                  for (j = 0; j < s.len(); j = j + 1)
                      if (rxq[base + j] !== s[j]) m = 1'b0;
                  if (m) begin
                      found = 1'b1;
                      break;
                  end
              end
              if (!found) begin
                  #(1000);        // 1 µs poll step (verify phases are ~0.9 s)
                  to = to + 1;
              end
          end
          chk(found, tag);
      end
  endtask

  // ============================================================================
  // Host BFM (AXI master 1) — drive on negedge, sample handshakes on posedge
  // ============================================================================
  localparam logic [31:0] EMRI_BASE = 32'h4000_2000;

  task automatic axi_wr(input logic [31:0] a, input logic [31:0] d);
      logic aw_done, w_done;
      begin
          @(negedge clk);
          h_awaddr = a; h_awvalid = 1'b1;
          h_wdata  = d; h_wvalid  = 1'b1;
          h_bready = 1'b1;
          aw_done = 1'b0; w_done = 1'b0;
          while (!(aw_done && w_done)) begin
              @(posedge clk);
              if (h_awvalid && h_awready) aw_done = 1'b1;
              if (h_wvalid  && h_wready)  w_done  = 1'b1;
          end
          @(negedge clk);
          h_awvalid = 1'b0; h_wvalid = 1'b0;
          while (!h_bvalid) @(posedge clk);
          @(negedge clk);
          h_bready = 1'b0;
      end
  endtask

  task automatic axi_rd(input logic [31:0] a, output logic [31:0] d);
      logic ar_done, r_done;
      begin
          @(negedge clk);
          h_araddr = a; h_arvalid = 1'b1; h_rready = 1'b1;
          ar_done = 1'b0;
          while (!ar_done) begin
              @(posedge clk);
              if (h_arvalid && h_arready) ar_done = 1'b1;
          end
          @(negedge clk);
          h_arvalid = 1'b0;
          d = 32'h0; r_done = 1'b0;
          while (!r_done) begin
              @(posedge clk);
              if (h_rvalid) begin
                  d      = h_rdata;
                  r_done = 1'b1;
              end
          end
          @(negedge clk);
          h_rready = 1'b0;
      end
  endtask

  // EMRI register access (word offset -> AXI address in the window)
  task automatic host_wr(input logic [15:0] word, input logic [31:0] d);
      begin
          axi_wr(EMRI_BASE + ({16'h0, word} << 2), d);
      end
  endtask

  task automatic host_rd(input logic [15:0] word, output logic [31:0] d);
      begin
          axi_rd(EMRI_BASE + ({16'h0, word} << 2), d);
      end
  endtask

  // ============================================================================
  // Session-JSON replayer (ethereal.efp-session.v0; emitted by
  // `ethctl --transport efp --emit-session`). Line-based: only lines carrying
  // the literal `{"op":"` marker are ops; every 32-bit value is a "0x........"
  // hex-string token scanned in order.
  //   write:  tokens = [addr, data]
  //   read:   tokens = [addr, mask, value]   (mask!=0 -> self-check)
  //   poll:   tokens = [addr, mask, value]   (re-read until match)
  //   stream: tokens = [addr, word0..wordN]  (each word -> OCC_WDATA)
  // ============================================================================
  localparam integer POLL_TO = 30_000_000;  // polls span ~83M-cycle verifies

  task automatic replay_session(input string path, input string tag);
      integer fd, n, i, k, w, ntok, nops, to;
      string line, tok, opn;
      logic [31:0] vals [0:79];
      logic [31:0] rd;
      begin
          fd = $fopen(path, "r");
          if (fd == 0) begin
              errors = errors + 1;
              $display("  FAIL: %0s — cannot open session file %0s", tag, path);
              return;
          end
          nops = 0;
          while (!$feof(fd)) begin
              n = $fgets(line, fd);
              if (n == 0) break;
              // locate the op marker
              i = -1;
              for (k = 0; k + 7 < line.len(); k = k + 1) begin
                  if (line.substr(k, k + 6) == "{\"op\":\"") begin
                      i = k;
                      break;
                  end
              end
              if (i < 0) continue;
              // op name right after the marker ('w'rite/'r'ead/'p'oll/'s'tream)
              opn = line.substr(i + 7, i + 10);
              // scan "0x........" hex tokens after the marker
              ntok = 0;
              for (k = i; k + 11 < line.len(); k = k + 1) begin
                  if (line.substr(k, k + 2) == "\"0x") begin
                      if (ntok < 80) begin
                          tok = line.substr(k + 3, k + 10);
                          n = $sscanf(tok, "%h", vals[ntok]);
                          ntok = ntok + 1;
                      end
                      k = k + 10;
                  end
              end
              if (ntok == 0) continue;
              nops = nops + 1;
              $display("  [%0t] %0s op%0d %0s addr=0x%02x ntok=%0d",
                       $time, tag, nops, opn, vals[0], ntok);
              if (opn == "writ") begin
                  if (ntok != 2) begin
                      errors = errors + 1;
                      $display("  FAIL: %0s — write op with %0d tokens", tag, ntok);
                  end else begin
                      host_wr(vals[0][15:0], vals[1]);
                  end
              end else if (opn == "read") begin
                  if (ntok != 3) begin
                      errors = errors + 1;
                      $display("  FAIL: %0s — read op with %0d tokens", tag, ntok);
                  end else begin
                      host_rd(vals[0][15:0], rd);
                      if (vals[1] != 32'h0)
                          chk((rd & vals[1]) == vals[2],
                              $sformatf("%0s: read @0x%02x = 0x%08x (mask 0x%08x want 0x%08x)",
                                        tag, vals[0], rd, vals[1], vals[2]));
                  end
              end else if (opn == "poll") begin
                  if (ntok != 3) begin
                      errors = errors + 1;
                      $display("  FAIL: %0s — poll op with %0d tokens", tag, ntok);
                  end else begin
                      to = 0;
                      host_rd(vals[0][15:0], rd);
                      while ((rd & vals[1]) != vals[2] && to < POLL_TO) begin
                          host_rd(vals[0][15:0], rd);
                          to = to + 1;
                      end
                      chk((rd & vals[1]) == vals[2],
                          $sformatf("%0s: poll @0x%02x matched (mask 0x%08x want 0x%08x)",
                                    tag, vals[0], vals[1], vals[2]));
                  end
              end else if (opn == "stre") begin
                  for (w = 1; w < ntok; w = w + 1) begin
                      $display("  [%0t] %0s stream word %0d = 0x%08x",
                               $time, tag, w - 1, vals[w]);
                      host_wr(vals[0][15:0], vals[w]);
                  end
              end else begin
                  errors = errors + 1;
                  $display("  FAIL: %0s — unknown op '%0s'", tag, opn);
              end
          end
          $fclose(fd);
          $display("  replayed %0d ops from %0s", nops, path);
      end
  endtask

  // ---- fabric observation (the REAL fabric outputs) ----------------------------
  task automatic observe_toggle(input string tag);
      integer k;
      logic s0, s1;
      begin
          s0 = 1'b0; s1 = 1'b0;
          for (k = 0; k < 128; k = k + 1) begin
              @(posedge clk);
              if (clb_out_obs[0] === 1'b0) s0 = 1'b1;
              if (clb_out_obs[0] === 1'b1) s1 = 1'b1;
          end
          chk(s0 && s1, tag);
      end
  endtask

  task automatic observe_const(input logic v, input string tag);
      integer k;
      logic bad;
      begin
          bad = 1'b0;
          for (k = 0; k < 128; k = k + 1) begin
              @(posedge clk);
              if (clb_out_obs[0] !== v) bad = 1'b1;
          end
          chk(!bad, tag);
      end
  endtask

