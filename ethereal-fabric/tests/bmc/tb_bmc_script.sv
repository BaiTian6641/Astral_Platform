// Module:      tb_bmc_script (testbench, self-checking)
// Description: E2-AST1 MCU scripted deployment — the BMC runs a
//              flash-resident deployment script through its own EFP/EMRI/OCC
//              machinery (no WASM runtime; phase-2 circuit-breaker degraded
//              demo). SIM-SCOPED command path per the emri-v0.md sec 3.6
//              precedent: EFP_CMD=SCRIPT (10) + EFP_REGION = script slot,
//              answered only by the firmware that installs the interpreter.
//
//                host BFM --AXI4--+
//                                 v
//                NEORV32 --XBUS--> eth_wb2axi --> eth_axi_xbar (2 masters)
//                                                    | 2 slaves
//                       +----------------------------+--------------------+
//                       v                                                 v
//             emri_axi_adapter -> emri_regfile          tb_scriptflash (model)
//             (EFP staging + status/err)                "external flash"
//                       | OCC master                    128 words: the
//                       v                                deployment scripts
//                 occ_top --fbus--> fabric_top (2x2 CLB)  (slot 0/1)
//                            +-> column_cfg_ram (readback target)
//
//              The firmware (bmc-fw/script/, real C) is the PRODUCTION daemon
//              (daemon.c: Ed25519 verify + OCC lifecycle) plus script/script.c
//              registered as the EFP_CMD_SCRIPT extension handler. The script
//              is GENERATED by script/gen_deploy_scripts.py (deterministic)
//              and read word-wise over XBUS at run time.
//
//              Scenario (script format v1; script/script.h):
//                0. boot: banner + EMRI MAGIC/CAP probe + EFP-SPI init +
//                   "daemon ready (script deploy)".
//                1. slot 0 (CRC-gated): start marker -> WAIT settle ->
//                   DEPLOY r0 = the daemon's OWN EFP_CMD_RUN path (Ed25519
//                   verify -> ALLOC -> BLANK -> LOAD (the host streams
//                   OCC_WDATA) -> READBACK -> RUNNING with EFP_ERR=0) ->
//                   POLL EFP_STATUS.state==RUNNING -> CHECK_ERR 0 -> "region
//                   0 RUNNING" marker -> WAIT (hold RUNNING so the TB can
//                   observe the real fabric) -> LOOP x2 markers (LOOPEND) ->
//                   STOP r0 -> POLL EFP_STATUS.state==STOPPED -> CHECK_ERR 0
//                   -> "region 0 stopped" marker -> END.
//                2. integrity negative: slot 1's header CRC corrupted in the
//                   flash model -> the interpreter refuses BEFORE any op
//                   ("script: err crc bad"), the command fails bad_cmd, and
//                   the fabric/region table are untouched.
//                3. image negative: slot 1 intact, host-staged SIGNATURE
//                   tampered -> the deploy reaches the Ed25519 gate, fails
//                   bad_sig (EFP_ERR=1 sticky, state ERROR), the script
//                   asserts it via CHECK_ERR and reports "bad_sig rejected";
//                   the fabric is untouched (no ALLOC/BLANK).
//
//              Register/observable contract: EFP_STATUS (RUNNING while the
//              script holds, STOPPED + busy=0 at the end), EFP_ERR (0 after
//              the scripted run, 1 sticky after the scripted reject),
//              MON_RECFG_COUNT.region0 == 1 (one completed deploy),
//              column_cfg_ram holds the image-A frame while RUNNING, and the
//              UART markers ("AST1: ...") prove the script's own ops.
//
//              SPEC ASK (NOT done here; spec changes are not this task's):
//              EFP_CMD=10 + R_SCRIPT_STATUS (proposed 0x3A) in emri-v0.md;
//              until then the slot index rides EFP_REGION and the script
//              verdict is UART-only (an interpreter error maps to EFP_ERR=6).
//              ASSUMPTION (TBD, 2026-09-12): the flash stand-in is a TB-local
//              non-volatile AXI model at 0x4001_0000 (same convention as the
//              E1-BMC2 fwupdate TB); real SPI flash + Boot-ROM anchoring stay
//              E2-SEC1/E2-BMC scope.
// Maintainer:  BaiTian6641
// Created:     2026-09-12
// Tags:        TESTBENCH
// Plan-Ref:    ethereal-spec/control/emri-v0.md sec 3.2/§3.4/§3.6;
//              ethereal-plan/subsystems/S05-BMC与EMRI-mFSM.md §2.2/§2.3;
//              ethereal-plan/phases/phase-2-异构与双平台.md §3 (circuit-breaker:
//              MCU scripted deployment while the WASM line is blocked).
// Notes:       Verilator --binary --timing (Makefile test-sv; same reason as
//              the other real-C-firmware BMC TBs). Two Ed25519 verifies
//              (~0.84 s sim each) dominate the run. UART bit time = 2 clk.
//              The WASM acceptance (wasmtime/WAMR Type-F container execution)
//              is NOT covered by this TB — it stays blocked on this machine.
