  // ============================================================================
  // Concurrent UART 8N1 receiver (idle-high, start bit low, LSB first)
  // ============================================================================
  localparam int MAXB = 8192;
  bit [7:0] rxq [0:MAXB-1];
  integer   rxn = 0;

  always @(negedge uart0_txd) begin : uart_rx
      integer i;
      logic [7:0] b;
      #(BIT_NS / 2);
      if (uart0_txd === 1'b0) begin
          b = 8'h00;
          for (i = 0; i < 8; i = i + 1) begin
              #(BIT_NS);
              b[i] = uart0_txd;
          end
          #(BIT_NS);
          if (uart0_txd === 1'b1 && rxn < MAXB) begin
              rxq[rxn] = b;
              rxn = rxn + 1;
          end
      end
  end

  // ============================================================================
  // Check helpers
  // ============================================================================
  integer errors = 0;

  // ============================================================================
  // Live UART trace (diagnostics): echo each newly received byte as the
  // firmware prints it, so a long/failing phase is visible immediately
  // (the firmware's own log is the ground truth for where it stopped).
  // ============================================================================
  localparam bit RX_TRACE = 1'b1;

  initial begin : rx_trace
      integer last, i;
      last = 0;
      forever begin
          #(100000);   // 100 us sim poll
          if (RX_TRACE && rxn != last) begin
              $write("[rx @%0dns +%0d] ", $time, rxn - last);
              for (i = last; i < rxn; i = i + 1) begin
                  if (rxq[i] == 8'h0a) $write("\n");
                  else if (rxq[i] < 8'h20 || rxq[i] > 8'h7e)
                      $write("<%02x>", rxq[i]);
                  else $write("%c", rxq[i]);
              end
              last = rxn;
          end
          if (!RX_TRACE) last = rxn;
      end
  end

  task automatic chk(input logic cond, input string msg);
      begin
          if (cond) $display("  ok: %0s", msg);
          else begin
              errors = errors + 1;
              $display("  FAIL: %0s", msg);
          end
      end
  endtask

  // Dump everything the firmware has printed so far (diagnostics for a failed
  // wait: the firmware's own trace is the ground truth for what went wrong).
  task automatic dump_uart;
      integer i;
      begin
          $write("  uart rx (%0d bytes): ", rxn);
          for (i = 0; i < rxn; i = i + 1) begin
              if (rxq[i] == 8'h0a) $write("\n");
              else if (rxq[i] < 8'h20 || rxq[i] > 8'h7e) $write("<%02x>", rxq[i]);
              else $write("%c", rxq[i]);
          end
          $write("\n");
      end
  endtask

  // Block until the received stream CONTAINS s (containment, like
  // tb_bmc_fwupdate) — the daemon's own logs interleave with the script's.
  task automatic wait_uart_contains(input string s, input string tag);
      integer to, base, j;
      logic found, m;
      begin
          to = 0;
          found = 1'b0;
          while (!found && to < 2000000) begin
              for (base = 0; base + s.len() <= rxn; base = base + 1) begin
                  m = 1'b1;
                  for (j = 0; j < s.len(); j = j + 1)
                      if (rxq[base + j] !== s[j]) m = 1'b0;
                  if (m) begin
                      found = 1'b1;
                      break;
                  end
              end
              if (!found) begin
                  #(1000);
                  to = to + 1;
              end
          end
          chk(found, tag);
          if (!found) dump_uart();
      end
  endtask

  // Count non-overlapping occurrences of s in the received stream (the LOOP
  // op's evidence: the body ran exactly N times).
  function automatic integer count_uart(input string s);
      integer base, j, n;
      logic m;
      begin
          n = 0;
          base = 0;
          while (base + s.len() <= rxn) begin
              m = 1'b1;
              for (j = 0; j < s.len(); j = j + 1)
                  if (rxq[base + j] !== s[j]) m = 1'b0;
              if (m) begin
                  n = n + 1;
                  base = base + s.len();
              end else begin
                  base = base + 1;
              end
          end
          count_uart = n;
      end
  endfunction

  // ============================================================================
  // Host BFM (AXI master 1) — drive on negedge, sample handshakes on posedge
  // ============================================================================
  localparam logic [31:0] EMRI_BASE = 32'h4000_2000;

  task automatic axi_wr(input logic [31:0] a, input logic [31:0] d);
      logic aw_done, w_done;
      begin
          @(negedge clk);
          h_awaddr = a; h_awvalid = 1'b1;
          h_wdata  = d; h_wvalid  = 1'b1;
          h_bready = 1'b1;
          aw_done = 1'b0; w_done = 1'b0;
          while (!(aw_done && w_done)) begin
              @(posedge clk);
              if (h_awvalid && h_awready) aw_done = 1'b1;
              if (h_wvalid  && h_wready)  w_done  = 1'b1;
          end
          @(negedge clk);
          h_awvalid = 1'b0; h_wvalid = 1'b0;
          while (!h_bvalid) @(posedge clk);
          @(negedge clk);
          h_bready = 1'b0;
      end
  endtask

  task automatic axi_rd(input logic [31:0] a, output logic [31:0] d);
      logic ar_done, r_done;
      begin
          @(negedge clk);
          h_araddr = a; h_arvalid = 1'b1; h_rready = 1'b1;
          ar_done = 1'b0;
          while (!ar_done) begin
              @(posedge clk);
              if (h_arvalid && h_arready) ar_done = 1'b1;
          end
          @(negedge clk);
          h_arvalid = 1'b0;
          d = 32'h0; r_done = 1'b0;
          while (!r_done) begin
              @(posedge clk);
              if (h_rvalid) begin
                  d      = h_rdata;
                  r_done = 1'b1;
              end
          end
          @(negedge clk);
          h_rready = 1'b0;
      end
  endtask

  task automatic host_wr(input logic [15:0] word, input logic [31:0] d);
      begin
          axi_wr(EMRI_BASE + ({16'h0, word} << 2), d);
      end
  endtask

  task automatic host_rd(input logic [15:0] word, output logic [31:0] d);
      begin
          axi_rd(EMRI_BASE + ({16'h0, word} << 2), d);
      end
  endtask

  // Poll EFP_STATUS until busy=0 (spec §3.2: the host MUST see busy=0 before
  // the next EFP_CMD write).
  task automatic host_wait_idle(input string tag);
      logic [31:0] s;
      integer to;
      begin
          to = 0;
          host_rd(R_EFP_STATUS_W, s);
          while (s[4] && to < 100000) begin
              host_rd(R_EFP_STATUS_W, s);
              to = to + 1;
          end
          chk(!s[4], tag);
      end
  endtask

  // ---- image staging (spec §3.2 step 1) ---------------------------------
  localparam int SEL_A        = 0;   // image A, valid signature
  localparam int SEL_A_TAMPER = 1;   // image A, tampered signature

  task automatic host_stage(input integer sel, input logic [31:0] words,
                            input logic [31:0] region);
      integer k;
      begin
          for (k = 0; k < 8; k = k + 1)
              host_wr(R_IMG_DIGEST + 16'(k), DAEMON_IMG_A_DIGEST[k]);
          for (k = 0; k < 16; k = k + 1)
              host_wr(R_IMG_SIG + 16'(k),
                      (sel == SEL_A_TAMPER) ? DAEMON_IMG_A_SIG_TAMPER[k]
                                            : DAEMON_IMG_A_SIG[k]);
          host_wr(R_EFP_IMG_WORDS, words);
          host_wr(R_EFP_REGION, region);
      end
  endtask

  // Stream the frame words through OCC_WDATA (spec §3.2 step 5: the host
  // streams while the daemon supervises OCC_STATUS in LOAD).
  task automatic host_stream;
      integer k;
      begin
          for (k = 0; k < DAEMON_IMG_A_NWORDS; k = k + 1)
              host_wr(R_OCC_WDATA, DAEMON_IMG_A_WORDS[k]);
      end
  endtask

  task automatic ring_script(input logic [31:0] slot);
      begin
          host_wr(R_EFP_REGION_W, slot);                 // script slot index
          host_wr(R_EFP_CMD_W, {24'h0, EFP_CMD_SCRIPT_W});
      end
  endtask

  // ---- fabric observation (the REAL fabric outputs) ---------------------
  task automatic observe_toggle(input string tag);
      integer k;
      logic s0, s1;
      begin
          s0 = 1'b0; s1 = 1'b0;
          for (k = 0; k < 128; k = k + 1) begin
              @(posedge clk);
              if (clb_out_obs[0] === 1'b0) s0 = 1'b1;
              if (clb_out_obs[0] === 1'b1) s1 = 1'b1;
          end
          chk(s0 && s1, tag);
      end
  endtask

  // ============================================================================
  // Test sequence (script format v1; bmc-fw/script/script.h)
  // ============================================================================
  logic [31:0] rd;
  logic [31:0] frame_shadow [0:IMG_A_WORDS-1];
  integer      k;
  logic        frame_ok;

  initial begin : main_seq
      // idle the host BFM + UART RX
      h_awvalid = 1'b0; h_awaddr = 32'h0;
      h_wvalid  = 1'b0; h_wdata  = 32'h0;
      h_bready  = 1'b0;
      h_arvalid = 1'b0; h_araddr = 32'h0;
      h_rready  = 1'b0;
      uart0_rxd = 1'b1;

      rst_n = 1'b0;
      repeat (20) @(posedge clk);
      rst_n = 1'b1;

      // ---- 0. boot ---------------------------------------------------------
      $display("[0] boot: script-deployment firmware on the real BMC chain");
      wait_uart_contains("bmc-fw script deploy demo boot\n", "boot banner");
      wait_uart_contains("EMRI MAGIC=45544852 CAP=00000001\n", "EMRI MAGIC/CAP probe");
      wait_uart_contains("efp-spi none (sim variant)\n",
                         "no EFP-SPI front-end in this variant (AXI host path)");
      wait_uart_contains("daemon ready (script deploy)\n",
                         "daemon poll loop + EFP_CMD_SCRIPT handler registered");

      // ---- 1. script slot 0: signed image deployed to region 0 ------------
      $display("[1] script slot 0 — deploy the signed image into region 0");
      host_stage(SEL_A, 32'(DAEMON_IMG_A_NWORDS), 32'd0);
      ring_script(32'd0);
      wait_uart_contains("script: run slot 0\n",
                         "slot header accepted (magic/version/length/CRC)");
      wait_uart_contains("script: deploy r0\n", "script DEPLOY r0 op issued");
      wait_uart_contains("verify ok\n", "Ed25519 signature verified (signed image)");
      wait_uart_contains("st LOAD\n", "deploy reached LOAD — host streams now");
      host_stream();
      wait_uart_contains("load ok\n", "OCC WRITE stream complete");
      wait_uart_contains("readback ok\n", "OCC READBACK CRC ok");
      wait_uart_contains("st RUNNING r0 done\n", "region 0 RUNNING");
      wait_uart_contains("script: poll 0016 ok\n", "script POLL saw EFP_STATUS");
      wait_uart_contains("script: err ok\n", "script CHECK_ERR = 0");
      wait_uart_contains("AST1: region 0 RUNNING\n", "script UART marker (RUNNING)");

      // The script holds RUNNING (WAIT op) — observe the real fabric + frame.
      observe_toggle("region 0 runs the signed image (clb_out_obs[0] toggles)");
      frame_ok = 1'b1;
      for (k = 0; k < IMG_A_WORDS; k = k + 1)
          if (u_cfgram.mem[k] !== DAEMON_IMG_A_WORDS[k]) frame_ok = 1'b0;
      chk(frame_ok, "column_cfg_ram holds the image-A frame while RUNNING");

      wait_uart_contains("AST1: tick\n", "LOOP body marker emitted");
      wait_uart_contains("AST1: region 0 stopped\n", "script UART marker (STOPPED)");
      wait_uart_contains("script: done ok\n", "script END reached, all checks ok");
      host_wait_idle("EFP_STATUS.busy cleared after the scripted command");
      host_rd(R_EFP_STATUS_W, rd);
      chk(rd[3:0] == EFP_S_STOPPED_W, "EFP_STATUS.state = STOPPED after script stop");
      host_rd(R_EFP_ERR_W, rd);
      chk(rd[7:0] == EFP_ERR_NONE, "EFP_ERR = 0 after the scripted run");
      chk(count_uart("AST1: tick\n") == 2, "LOOP op executed its body exactly twice");
      host_rd(R_MON_RECFG_COUNT, rd);
      chk(rd[15:0] == 32'd1, "MON_RECFG_COUNT.region0 == 1 (one completed deploy)");

      // ---- 2. integrity negative: corrupted script slot 1 CRC -------------
      $display("[2] script slot 1 with a corrupted header CRC — refused");
      for (k = 0; k < IMG_A_WORDS; k = k + 1) frame_shadow[k] = u_cfgram.mem[k];
      u_scriptflash.mem[SLOT_WORDS + 3] = u_scriptflash.mem[SLOT_WORDS + 3] ^ 32'h1;
      ring_script(32'd1);
      wait_uart_contains("script: err crc bad\n",
                         "interpreter CRC gate refused the slot (no op ran)");
      wait_uart_contains("err bad_cmd\n", "EFP_CMD_SCRIPT command failed with bad_cmd");
      host_wait_idle("busy cleared after the refused script");
      host_rd(R_EFP_ERR_W, rd);
      chk(rd[7:0] == EFP_ERR_BAD_CMD, "EFP_ERR = bad_cmd (6) for the refused script");
      host_rd(R_EFP_STATUS_W, rd);
      chk(rd[3:0] == EFP_S_ERROR_W, "EFP_STATUS.state = ERROR after the refusal");
      host_rd(R_MON_RECFG_COUNT, rd);
      chk(rd[15:0] == 32'd1, "no deploy happened (MON_RECFG_COUNT.region0 still 1)");
      // restore slot 1's header CRC
      u_scriptflash.mem[SLOT_WORDS + 3] = u_scriptflash.mem[SLOT_WORDS + 3] ^ 32'h1;
      chk(u_scriptflash.mem[SLOT_WORDS + 0] == SCRIPT_MAGIC, "slot 1 still intact");

      // ---- 3. image negative: tampered signature, script asserts bad_sig --
      $display("[3] script slot 1 with a TAMPERED staged signature — bad_sig");
      host_stage(SEL_A_TAMPER, 32'(DAEMON_IMG_A_NWORDS), 32'd0);
      ring_script(32'd1);
      wait_uart_contains("script: run slot 1\n", "slot 1 accepted after CRC restore");
      wait_uart_contains("script: deploy r0\n", "script DEPLOY r0 op issued");
      wait_uart_contains("err bad_sig\n", "Ed25519 gate refused the tampered image");
      wait_uart_contains("script: err ok\n", "script CHECK_ERR matched bad_sig (1)");
      wait_uart_contains("AST1: bad_sig rejected\n", "script UART marker (reject)");
      wait_uart_contains("script: done ok\n", "reject script END reached, check ok");
      host_wait_idle("busy cleared after the reject script");
      host_rd(R_EFP_ERR_W, rd);
      chk(rd[7:0] == EFP_ERR_BAD_SIG, "EFP_ERR = bad_sig (1) sticky after the script");
      host_rd(R_EFP_STATUS_W, rd);
      chk(rd[3:0] == EFP_S_ERROR_W, "EFP_STATUS.state = ERROR (deploy refused)");
      host_rd(R_MON_RECFG_COUNT, rd);
      chk(rd[15:0] == 32'd1, "rejected deploy never reached RUNNING (count still 1)");
      frame_ok = 1'b1;
      for (k = 0; k < IMG_A_WORDS; k = k + 1)
          if (u_cfgram.mem[k] !== frame_shadow[k]) frame_ok = 1'b0;
      chk(frame_ok, "rejected deploy left the fabric config untouched");

      // ---- report ----------------------------------------------------------
      if (errors == 0)
          $display("TEST PASSED: E2-AST1 MCU scripted deployment — flash script (CRC-gated) -> EFP_CMD_SCRIPT -> signed image deployed to region 0 (RUNNING, EFP_ERR=0) -> UART markers (LOOP) -> STOPPED; corrupted script + tampered signature refused");
      else
          $display("TEST FAILED: %0d errors", errors);
      $finish;
  end

  // -- Watchdog -------------------------------------------------------------
  initial begin
      // 2 Ed25519 verifies (~0.84 s sim each) + OCC deploys: ~5 s sim.
      repeat (20) #(1000000000);   // 20 s hard cap
      $display("TEST FAILED: watchdog timeout (rxn=%0d errors=%0d)", rxn, errors);
      $finish;
  end

endmodule

// ============================================================================
// tb_scriptflash — TB-local "external flash" stand-in (SIM MODEL, not RTL):
// an AXI4-Lite slave serving a word array. The storage has NO reset clear
// (non-volatile: the deployment scripts must survive the TB reset pulse); the
// TB preloads/corrupts it hierarchically (u_scriptflash.mem[...]) while the
// CPU is quiescent. Same shape as tb_fwflash (tb_bmc_fwupdate.sv).
// ============================================================================
module tb_scriptflash #(
    parameter logic [31:0] BASE = 32'h4001_0000,
    parameter int          WORDS = 128
) (
    input  logic        clk_i,
    input  logic        rst_ni,
    input  logic        s_axi_awvalid,
    output logic        s_axi_awready,
    input  logic [31:0] s_axi_awaddr,
    input  logic        s_axi_wvalid,
    output logic        s_axi_wready,
    input  logic [31:0] s_axi_wdata,
    input  logic [3:0]  s_axi_wstrb,
    output logic        s_axi_bvalid,
    input  logic        s_axi_bready,
    output logic [1:0]  s_axi_bresp,
    input  logic        s_axi_arvalid,
    output logic        s_axi_arready,
    input  logic [31:0] s_axi_araddr,
    output logic        s_axi_rvalid,
    input  logic        s_axi_rready,
    output logic [31:0] s_axi_rdata,
    output logic [1:0]  s_axi_rresp
);
    // Non-volatile storage (deliberately NO reset clear).
    logic [31:0] mem [0:WORDS-1];

    typedef enum logic [1:0] { S_IDLE = 2'd0, S_WRB = 2'd1, S_RD = 2'd2 } st_e;
    st_e st;
    logic [31:0] raddr_q;

    assign s_axi_awready = (st == S_IDLE) && s_axi_awvalid && s_axi_wvalid;
    assign s_axi_wready  = s_axi_awready;
    assign s_axi_arready = (st == S_IDLE) && s_axi_arvalid &&
                           !(s_axi_awvalid && s_axi_wvalid);

    always_ff @(posedge clk_i or negedge rst_ni) begin
        if (!rst_ni) begin
            st           <= S_IDLE;
            raddr_q      <= 32'h0;
            s_axi_bvalid <= 1'b0;
            s_axi_rvalid <= 1'b0;
            s_axi_bresp  <= 2'b00;
            s_axi_rresp  <= 2'b00;
            s_axi_rdata  <= 32'h0;
        end else begin
            s_axi_bvalid <= 1'b0;   // default: pulse unless held below
            s_axi_rvalid <= 1'b0;
            case (st)
                S_IDLE: begin
                    if (s_axi_awvalid && s_axi_wvalid) begin
                        // apply the (masked) write ONCE, at accept time
                        for (int b = 0; b < 4; b++) begin
                            if (s_axi_wstrb[b]) begin
                                mem[(s_axi_awaddr - BASE) >> 2][b*8 +: 8] <=
                                    s_axi_wdata[b*8 +: 8];
                            end
                        end
                        s_axi_bvalid <= 1'b1;
                        s_axi_bresp  <= 2'b00;  // OKAY
                        st <= S_WRB;
                    end else if (s_axi_arvalid) begin
                        raddr_q <= s_axi_araddr;
                        st      <= S_RD;
                    end
                end
                S_WRB: begin
                    s_axi_bvalid <= 1'b1;  // hold B until bready
                    if (s_axi_bready) st <= S_IDLE;
                end
                S_RD: begin
                    s_axi_rvalid <= 1'b1;
                    s_axi_rdata  <= mem[(raddr_q - BASE) >> 2];
                    s_axi_rresp  <= 2'b00;  // OKAY
                    if (s_axi_rready) st <= S_IDLE;
                end
                default: st <= S_IDLE;
            endcase
        end
    end
endmodule

