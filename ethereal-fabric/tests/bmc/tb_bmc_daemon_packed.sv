  // -- Packed-image test vectors (DATA words + digest/sig + tampered sig) --------
  `include "tb_daemon_packed_vectors.svh"

  // ============================================================================
  // Concurrent UART 8N1 receiver (idle-high, start bit low, LSB first)
  // ============================================================================
  localparam int MAXB = 8192;
  bit [7:0] rxq [0:MAXB-1];
  integer   rxn = 0;   // received count

  always @(negedge uart0_txd) begin : uart_rx
      integer i;
      logic [7:0] b;
      #(BIT_NS / 2);
      if (uart0_txd === 1'b0) begin
          b = 8'h00;
          for (i = 0; i < 8; i = i + 1) begin
              #(BIT_NS);
              b[i] = uart0_txd;
          end
          #(BIT_NS);
          if (uart0_txd === 1'b1 && rxn < MAXB) begin
              rxq[rxn] = b;
              rxn = rxn + 1;
          end
      end
  end

  // ============================================================================
  // Check helpers (chk-count style of tb_ethctl_replay)
  // ============================================================================
  integer errors = 0;
  task automatic chk(input logic cond, input string msg);
      begin
          if (cond) $display("  ok: %0s", msg);
          else begin
              errors = errors + 1;
              $display("  FAIL: %0s", msg);
          end
      end
  endtask

  // Spot-check: block (bounded) until the daemon UART log CONTAINS string s.
  // (Containment, not exact-match, tb_ethctl_replay style.)
  task automatic wait_uart_contains(input string s, input string tag);
      integer to, base, j;
      logic found, m;
      begin
          to = 0;
          found = 1'b0;
          while (!found && to < 4000000) begin
              for (base = 0; base + s.len() <= rxn; base = base + 1) begin
                  m = 1'b1;
                  for (j = 0; j < s.len(); j = j + 1)
                      if (rxq[base + j] !== s[j]) m = 1'b0;
                  if (m) begin
                      found = 1'b1;
                      break;
                  end
              end
              if (!found) begin
                  #(1000);        // 1 µs poll step (verify phases are ~0.9 s)
                  to = to + 1;
              end
          end
          chk(found, tag);
      end
  endtask

  // ============================================================================
  // Host BFM (AXI master 1) — drive on negedge, sample handshakes on posedge
  // ============================================================================
  localparam logic [31:0] EMRI_BASE = 32'h4000_2000;

  task automatic axi_wr(input logic [31:0] a, input logic [31:0] d);
      logic aw_done, w_done;
      begin
          @(negedge clk);
          h_awaddr = a; h_awvalid = 1'b1;
          h_wdata  = d; h_wvalid  = 1'b1;
          h_bready = 1'b1;
          aw_done = 1'b0; w_done = 1'b0;
          while (!(aw_done && w_done)) begin
              @(posedge clk);
              if (h_awvalid && h_awready) aw_done = 1'b1;
              if (h_wvalid  && h_wready)  w_done  = 1'b1;
          end
          @(negedge clk);
          h_awvalid = 1'b0; h_wvalid = 1'b0;
          while (!h_bvalid) @(posedge clk);
          @(negedge clk);
          h_bready = 1'b0;
      end
  endtask

  task automatic axi_rd(input logic [31:0] a, output logic [31:0] d);
      logic ar_done, r_done;
      begin
          @(negedge clk);
          h_araddr = a; h_arvalid = 1'b1; h_rready = 1'b1;
          ar_done = 1'b0;
          while (!ar_done) begin
              @(posedge clk);
              if (h_arvalid && h_arready) ar_done = 1'b1;
          end
          @(negedge clk);
          h_arvalid = 1'b0;
          d = 32'h0; r_done = 1'b0;
          while (!r_done) begin
              @(posedge clk);
              if (h_rvalid) begin
                  d      = h_rdata;
                  r_done = 1'b1;
              end
          end
          @(negedge clk);
          h_rready = 1'b0;
      end
  endtask

  // EMRI register access (word offset -> AXI address in the window)
  task automatic host_wr(input logic [15:0] word, input logic [31:0] d);
      begin
          axi_wr(EMRI_BASE + ({16'h0, word} << 2), d);
      end
  endtask

  task automatic host_rd(input logic [15:0] word, output logic [31:0] d);
      begin
          axi_rd(EMRI_BASE + ({16'h0, word} << 2), d);
      end
  endtask

  // Poll EFP_STATUS until busy=0 (spec §3.2: host MUST wait busy=0 before the
  // next EFP_CMD write).
  task automatic host_wait_idle;
      logic [31:0] s;
      integer to;
      begin
          to = 0;
          host_rd(R_EFP_STATUS, s);
          while (s[4] && to < 100000) begin
              host_rd(R_EFP_STATUS, s);
              to = to + 1;
          end
          chk(!s[4], "EFP_STATUS.busy cleared (host may issue next command)");
      end
  endtask

  // Poll EFP_STATUS until state[3:0]==st. 1 µs poll step (an unpaced AXI poll
  // loop is ~80 ns/iter — a flat iteration bound would expire mid-VERIFY;
  // VERIFY is ~0.84 s sim, so 4M x 1 µs = 4 s of headroom).
  task automatic host_wait_state(input logic [3:0] st, input string tag);
      logic [31:0] s;
      integer to;
      begin
          to = 0;
          host_rd(R_EFP_STATUS, s);
          while (s[3:0] != st && to < 4000000) begin
              #(1000);
              host_rd(R_EFP_STATUS, s);
              to = to + 1;
          end
          chk(s[3:0] == st, tag);
      end
  endtask

  // Poll EFP_STATUS until state==st AND busy==0 (terminal of a command).
  // Same 1 µs pacing as host_wait_state.
  task automatic host_wait_terminal(input logic [3:0] st, input string tag);
      logic [31:0] s;
      integer to;
      begin
          to = 0;
          host_rd(R_EFP_STATUS, s);
          while ((s[3:0] != st || s[4]) && to < 4000000) begin
              #(1000);
              host_rd(R_EFP_STATUS, s);
              to = to + 1;
          end
          chk(s[3:0] == st && !s[4], tag);
      end
  endtask

  // ---- packed image staging (spec §3.3 staged metadata) -----------------------
  task automatic host_stage_packed(input logic tamper, input logic [31:0] region);
      integer k;
      begin
          for (k = 0; k < 8; k = k + 1)
              host_wr(R_IMG_DIGEST + 16'(k), DAEMON_IMGP_DIGEST[k]);
          for (k = 0; k < 16; k = k + 1)
              host_wr(R_IMG_SIG + 16'(k),
                      tamper ? DAEMON_IMGP_SIG_TAMPER[k] : DAEMON_IMGP_SIG[k]);
          host_wr(R_EFP_IMG_WORDS, 32'(DAEMON_IMGP_NWORDS));  // per-column DATA words
          host_wr(R_EFP_IMG_COLS, 32'd1);                      // 1 column (col 0)
          host_wr(R_EFP_REGION, region);
      end
  endtask

  // Stream the column's DATA words through OCC_WDATA (spec §3.3 step 3).
  task automatic host_stream_packed;
      integer k;
      begin
          for (k = 0; k < DAEMON_IMGP_NWORDS; k = k + 1)
              host_wr(R_OCC_WDATA, DAEMON_IMGP_WORDS[k]);
      end
  endtask

  // ---- fabric observation (the REAL fabric outputs) ----------------------------
  task automatic observe_toggle(input string tag);
      integer k;
      logic s0, s1;
      begin
          s0 = 1'b0; s1 = 1'b0;
          for (k = 0; k < 128; k = k + 1) begin
              @(posedge clk);
              if (clb_out_obs[0] === 1'b0) s0 = 1'b1;
              if (clb_out_obs[0] === 1'b1) s1 = 1'b1;
          end
          chk(s0 && s1, tag);
      end
  endtask

  task automatic observe_const(input logic v, input string tag);
      integer k;
      logic bad;
      begin
          bad = 1'b0;
          for (k = 0; k < 128; k = k + 1) begin
              @(posedge clk);
              if (clb_out_obs[0] !== v) bad = 1'b1;
          end
          chk(!bad, tag);
      end
  endtask

  // Pulse the fabric region user-reset (fab_usr_rst_n, tb_bmc_axi_fabric
  // pattern): the image's FFs take ff_rst_val deterministically post-config.
  task automatic fab_region_reset;
      begin
          fab_usr_rst_n = 1'b0;
          repeat (10) @(posedge clk);
          fab_usr_rst_n = 1'b1;
          repeat (4) @(posedge clk);
      end
  endtask

  // dec_done is a 1-cycle pulse; count them (run_packed col0 = BLANK decode +
  // WRITE decode = 2; the stop blank adds a 3rd).
  integer dec_done_count = 0;
  always @(posedge clk) if (dec_done) dec_done_count = dec_done_count + 1;

  task automatic wait_dec_done(input integer n, input string tag);
      integer k;
      begin
          k = 0;
          while (dec_done_count < n && k < 4000000) begin
              @(posedge clk);
              k = k + 1;
          end
          chk(dec_done_count >= n, tag);
      end
  endtask

  // ============================================================================
  // Test sequence (spec §3.3 run_packed flow)
  // ============================================================================
  logic [31:0] rd;

  initial begin : main_seq
      // idle the host BFM + UART RX
      h_awvalid = 1'b0; h_awaddr = 32'h0;
      h_wvalid  = 1'b0; h_wdata  = 32'h0;
      h_bready  = 1'b0;
      h_arvalid = 1'b0; h_araddr = 32'h0;
      h_rready  = 1'b0;
      uart0_rxd = 1'b1;

      rst_n = 1'b0;
      repeat (20) @(posedge clk);
      rst_n = 1'b1;

      // ---- 0. boot: banner + Ed25519 selftest + EMRI probe + daemon up --------
      $display("[0] boot (selftest = 2 verifies, ~1.7 s sim)");
      wait_uart_contains("bmc-fw v0.2 daemon boot\n", "boot banner");
      wait_uart_contains("ed25519 selftest OK\n", "boot Ed25519 selftest");
      wait_uart_contains("daemon ready\n", "daemon poll loop entered");

      // ---- 1. run_packed image P (TFF), 1 column, region 0 --------------------
      $display("[1] run_packed image P (packed TFF col0) — region 0, 1 column");
      host_stage_packed(1'b0, 32'h0000_0000);
      host_wr(R_EFP_CMD, {24'h0, EFP_CMD_RUN_PACKED});
      wait_uart_contains("cmd run_packed\n", "run_packed: doorbell accepted");
      // spec §3.3 step 3 (column 0): poll state==LOAD (the daemon arms the OCC
      // WRITE before LOAD becomes visible), then stream the DATA words.
      host_wait_state(EFP_S_LOAD, "run_packed: state==LOAD (col 0 WRITE armed)");
      wait_uart_contains("st LOAD c0\n", "run_packed: UART st LOAD c0");
      host_stream_packed();
      host_wait_terminal(EFP_S_RUNNING, "run_packed: terminal RUNNING (busy=0)");
      host_rd(R_EFP_STATUS, rd);
      chk(rd[3:0] == EFP_S_RUNNING && rd[5] == 1'b1,
          "EFP_STATUS = RUNNING + done");
      host_rd(R_EFP_ERR, rd);
      chk(rd[7:0] == EFP_ERR_NONE, "EFP_ERR = none (READBACK CRC ok)");
      wait_uart_contains("st READBACK c0\n", "run_packed: UART st READBACK c0");
      wait_uart_contains("readback c0 ok\n", "run_packed: UART readback c0 ok");
      wait_uart_contains("st RUNNING r0 done\n", "run_packed: UART RUNNING");
      // the WRITE decode finished (2nd decode: BLANK #1, WRITE #2), then the
      // fabric COMPUTES: region-reset pulse + the TFF toggles on clb_out_obs[0].
      wait_dec_done(2, "run_packed: BLANK+WRITE frame_decoder decodes done");
      fab_region_reset();
      observe_toggle("run_packed: clb_out_obs[0] toggles (TFF on real fabric)");

      // ---- 2. negative: tampered signature -> bad_sig, fabric untouched -------
      $display("[2] run_packed with TAMPERED signature");
      host_stage_packed(1'b1, 32'h0000_0000);
      host_wr(R_EFP_CMD, {24'h0, EFP_CMD_RUN_PACKED});
      wait_uart_contains("cmd run_packed\nst VERIFY\n", "tamper: accepted + VERIFY");
      wait_uart_contains("err bad_sig\nst ERROR\n", "tamper: EFP_ERR=bad_sig, ERROR");
      host_wait_idle();
      host_rd(R_EFP_ERR, rd);
      chk(rd[7:0] == EFP_ERR_BAD_SIG, "EFP_ERR = bad_sig (1)");
      host_rd(R_EFP_STATUS, rd);
      chk(rd[3:0] == EFP_S_ERROR, "EFP_STATUS = ERROR");
      observe_toggle("tamper: fabric untouched (P still toggling)");

      // ---- 3. stop region 0 (packed per-column blank path) ---------------------
      $display("[3] stop region 0 (packed per-column BLANK)");
      host_wr(R_EFP_REGION, 32'h0000_0000);
      host_wr(R_EFP_CMD, {24'h0, EFP_CMD_STOP});
      wait_uart_contains("cmd stop\nst BLANK c0\nblank c0 ok\nst STOPPED r0\n",
                         "stop: per-column BLANK -> STOPPED");
      host_wait_idle();
      host_rd(R_EFP_STATUS, rd);
      chk(rd[3:0] == EFP_S_STOPPED, "EFP_STATUS = STOPPED");
      wait_dec_done(3, "stop: blank frame_decoder decode done");
      fab_region_reset();
      observe_const(1'b0, "stopped: clb_out_obs[0] constant 0 (column blanked)");

      // ---- report ---------------------------------------------------------------
      if (errors == 0)
          $display("TEST PASSED: E1-RUN2 daemon run_packed — packed TFF deployed through OCC_DECODE loop, toggles on real fabric, READBACK CRC ok, bad_sig rejected, per-column stop blank");
      else
          $display("TEST FAILED: %0d errors", errors);
      $finish;
  end

  // -- Watchdog -------------------------------------------------------------------
  initial begin
      // Total sim ≈ 4 verify-equivalents × ~0.84 s + deploys ≈ ~4 s sim.
      repeat (15) #(1000000000);   // 15 s hard cap
      $display("TEST FAILED: watchdog timeout (rxn=%0d errors=%0d)",
               rxn, errors);
      $finish;
  end

