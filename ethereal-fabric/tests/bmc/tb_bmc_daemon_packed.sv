// Module:      tb_bmc_daemon_packed (testbench, self-checking)
// Description: E1-RUN2 packed-deploy CAPSTONE — the BMC firmware daemon drives
//              the emri-v0.md §3.3 (v0.3) EFP run_packed flow on the REAL
//              chain, deploying BIT-PACKED production frames (frame_map
//              format) through the per-column OCC_DECODE loop (§3.1):
//
//                host BFM --AXI4--+
//                                 v
//                NEORV32 --XBUS--> eth_wb2axi --> eth_axi_xbar (2 masters)
//                                                    | 1 slave (512 B window)
//                                           emri_axi_adapter --> emri_regfile
//                                                    | OCC master    | dec_start
//                                              occ_top --fbus--> frame_decoder
//                                                    |               | cfg
//                                                    +--> column_cfg_ram
//                                                    (readback)      v
//                                                              fabric_top (2x2 CLB)
//
//              The host BFM plays ethctl --transport efp run_packed: stage
//              IMG_DIGEST/IMG_SIG/EFP_IMG_WORDS(per-column DATA count)/
//              EFP_IMG_COLS/EFP_REGION, ring EFP_CMD=run_packed, then PER
//              COLUMN: poll EFP_STATUS.state==LOAD and stream the column's
//              DATA words through OCC_WDATA while the daemon supervises
//              OCC_STATUS. The daemon (real C firmware, Ed25519 verify
//              against keyring.h) supervises VERIFY->ALLOC->BLANK(per col)->
//              LOAD(per col)->READBACK(per col)->RUNNING.
//
//              Scenario (spec §3.3):
//                1. run_packed img P (TFF, packed col0 frame from
//                   pack_tb_frames.py), 1 column @ region 0 -> RUNNING;
//                   fabric region-reset pulse (fab_usr_rst_n, same pattern as
//                   tb_bmc_axi_fabric) -> clb_out_obs[0] TOGGLES on the real
//                   fabric; READBACK CRC ok.
//                2. run_packed with tampered sig -> EFP_ERR=bad_sig, ERROR,
//                   fabric untouched.
//                3. stop region 0 -> STOPPED; the packed region is blanked
//                   PER COLUMN (occ_blank_packed path), output blanked.
//
//              The daemon's UART log is SPOT-CHECKED (containment of the key
//              lines, tb_ethctl_replay style) — not exact-matched.
// Maintainer:  BaiTian6641
// Created:     2026-09-02
// Tags:        TESTBENCH
// Plan-Ref:    ethereal-spec/control/emri-v0.md §3.3 (run_packed) + §3.1
//              (OCC_DECODE); ethereal-plan/subsystems/S05-BMC与EMRI-mFSM.md §2.3
// Notes:       Verilator --binary --timing (Makefile test-sv): a real Ed25519
//              verify is ~83M cycles on the iterative-mul NEORV32 netlist —
//              hours under iverilog, ~1 min/verify here (ADR-018 §7.5
//              exemption: cycle count, not language). Packed image
//              vectors are regenerated by gen_daemon_vectors.py --svh-packed
//              from generated/tb_frames/img_a_col0.hex (CRC16 tail dropped;
//              EFP_IMG_WORDS = 34 DATA words). UART bit time = 2 clk.
