// Module:      tb_bmc_daemon (testbench, self-checking)
// Description: E1-RUN2 CAPSTONE — the BMC firmware daemon drives the full
//              emri-v0.md §3.2 EFP flow on the REAL chain, with a host BFM as
//              the SECOND AXI master:
//
//                host BFM --AXI4--+
//                                 v
//                NEORV32 --XBUS--> eth_wb2axi --> eth_axi_xbar (2 masters)
//                                                    | 1 slave (512 B window)
//                                           emri_axi_adapter --> emri_regfile
//                                                    | OCC master
//                                              occ_top --fbus--> fabric_top (2x2 CLB)
//                                                            +-> column_cfg_ram
//                                                              (readback target)
//
//              The host BFM plays ethctl: stage IMG_DIGEST/IMG_SIG/
//              EFP_IMG_WORDS/EFP_REGION, ring EFP_CMD, stream OCC_WDATA while
//              the daemon is in LOAD, poll EFP_STATUS/EFP_ERR. The daemon
//              (real C firmware, Ed25519 verify against keyring.h) supervises
//              VERIFY->ALLOC->BLANK->LOAD->READBACK->RUNNING.
//
//              Scenario (spec §3.2):
//                1. run image A (TFF) auto-alloc  -> RUNNING, clb_out[0] toggles
//                  1a. MON_RECFG_COUNT.region0 == 1 (deploy notify, v0.6 §3.8)
//                  1b. CAP_DECL_IO over-declared -> EFP_ERR=11, no BLANK,
//                      no fabric mutation; the next deploy still succeeds
//                  1c. ctx_save/ctx_restore (v0.7) -> PAUSED + frozen for 512
//                      cycles, restore -> RUNNING + toggling; restore while
//                      RUNNING / save on FREE -> EFP_ERR=13
//                2. restart                       -> re-verify+reload, toggles
//                3. stop r0                       -> STOPPED, output blanked
//                4. run image B (const1) auto     -> RUNNING, clb_out[0] == 1
//                5. run with tampered sig         -> EFP_ERR=bad_sig, ERROR,
//                                                    fabric untouched
//                6. run on RUNNING region 0       -> EFP_ERR=region_full
//                7. abort                         -> IDLE, region blanked
//                8. forced reconfig spike         -> MON_ANOM_STATUS throttle;
//                      run to that region -> EFP_ERR=12, no ALLOC
//
//              The daemon's UART log (state transitions + errors) is
//              exact-matched byte-for-byte, in order, at every phase.
//
//              Frame format: v0 cfg-addr-addressed (fbus drives fabric_top's
//              cfg port directly AND the column_cfg_ram readback model) —
//              same format as tb_mgmt_hotswap; the bit-packed frame_decoder
//              path is covered by tb_bmc_axi_fabric. Region 0 frame base =
//              0x0000 (OCC_FRAME_ADDR.region_id[15:12]).
// Maintainer:  BaiTian6641
// Created:     2026-09-01
// Tags:        TESTBENCH
// Plan-Ref:    ethereal-spec/control/emri-v0.md §3.2 (EFP command block);
//              ethereal-plan/subsystems/S05-BMC与EMRI-mFSM.md §2.3 (E1-RUN2)
// Notes:       Simulated via Verilator --binary --timing (Makefile test-sv):
//              a real Ed25519 verify is ~83M cycles on the iterative-mul
//              NEORV32 netlist — hours under iverilog, ~1 min/verify with
//              the Verilator build (sim-only slowness; ~1.6 s @50 MHz real
//              silicon per verify). ADR-018 §7.5 iverilog constraint exempted
//              for cycle count, not language. Image/digest/signature vectors
//              are regenerated by gen_daemon_vectors.py (deterministic
//              fixed-seed key; the C keyring holds the matching public key).
//              UART bit time = 2 clk (NEORV32 reset defaults PRSC=0/BAUD=0).
