  // -- Daemon test vectors (image words + digest/sig + tampered sig) -------------
  `include "tb_daemon_vectors.svh"

  // ============================================================================
  // Concurrent UART 8N1 receiver (idle-high, start bit low, LSB first)
  // ============================================================================
  localparam int MAXB = 8192;
  bit [7:0] rxq [0:MAXB-1];
  integer   rxn = 0;   // received count
  integer   rxr = 0;   // consumed count (expect_uart)

  always @(negedge uart0_txd) begin : uart_rx
      integer i;
      logic [7:0] b;
      #(BIT_NS / 2);
      if (uart0_txd === 1'b0) begin
          b = 8'h00;
          for (i = 0; i < 8; i = i + 1) begin
              #(BIT_NS);
              b[i] = uart0_txd;
          end
          #(BIT_NS);
          if (uart0_txd === 1'b1 && rxn < MAXB) begin
              rxq[rxn] = b;
              rxn = rxn + 1;
          end
      end
  end

  // ============================================================================
  // Check helpers
  // ============================================================================
  integer errors = 0;
  // v0.7 sec 3.9 context stages (E2-FAB3b): freeze-window probe locals.
  integer ctx_k;
  logic   ctx_ref, ctx_frozen_bad;
  // v0.8 sec 3.10 lock-matrix stage locals (E2-SEC1b).
  logic [31:0] lkm_shadow;
  integer      lkm_to;
  task automatic chk(input logic cond, input logic [511:0] msg);
      begin
          if (cond) $display("  ok: %0s", msg);
          else begin
              errors = errors + 1;
              $display("  FAIL: %0s", msg);
          end
      end
  endtask

  // Exact-match the next s.len() UART bytes (in order) against string s.
  // Blocks (with a generous bound) until the daemon has printed them.
  task automatic expect_uart(input string s, input logic [511:0] tag);
      integer k;
      integer to;
      integer n;
      begin
          n  = s.len();
          to = 0;
          while ((rxn - rxr) < n && to < 4000000) begin
              #(1000);            // 1 µs poll step (verify phases are ~0.9 s)
              to = to + 1;
          end
          if ((rxn - rxr) < n) begin
              errors = errors + 1;
              $display("  FAIL: %0s — UART timeout (have %0d of %0d bytes)",
                       tag, rxn - rxr, n);
          end else begin
              for (k = 0; k < n; k = k + 1) begin
                  if (rxq[rxr + k] !== s[k]) begin
                      errors = errors + 1;
                      $display("  FAIL: %0s — byte %0d = 0x%02x, expected 0x%02x",
                               tag, k, rxq[rxr + k], s[k]);
                  end
              end
              rxr = rxr + n;
              $display("  ok: %0s", tag);
          end
      end
  endtask

  // ============================================================================
  // Host BFM (AXI master 1) — drive on negedge, sample handshakes on posedge
  // ============================================================================
  localparam logic [31:0] EMRI_BASE = 32'h4000_2000;

  task automatic axi_wr(input logic [31:0] a, input logic [31:0] d);
      logic aw_done, w_done;
      begin
          @(negedge clk);
          h_awaddr = a; h_awvalid = 1'b1;
          h_wdata  = d; h_wvalid  = 1'b1;
          h_bready = 1'b1;
          aw_done = 1'b0; w_done = 1'b0;
          while (!(aw_done && w_done)) begin
              @(posedge clk);
              if (h_awvalid && h_awready) aw_done = 1'b1;
              if (h_wvalid  && h_wready)  w_done  = 1'b1;
          end
          @(negedge clk);
          h_awvalid = 1'b0; h_wvalid = 1'b0;
          while (!h_bvalid) @(posedge clk);
          @(negedge clk);
          h_bready = 1'b0;
      end
  endtask

  task automatic axi_rd(input logic [31:0] a, output logic [31:0] d);
      logic ar_done, r_done;
      begin
          @(negedge clk);
          h_araddr = a; h_arvalid = 1'b1; h_rready = 1'b1;
          ar_done = 1'b0;
          while (!ar_done) begin
              @(posedge clk);
              if (h_arvalid && h_arready) ar_done = 1'b1;
          end
          @(negedge clk);
          h_arvalid = 1'b0;
          d = 32'h0; r_done = 1'b0;
          while (!r_done) begin
              @(posedge clk);
              if (h_rvalid) begin
                  d      = h_rdata;
                  r_done = 1'b1;
              end
          end
          @(negedge clk);
          h_rready = 1'b0;
      end
  endtask

  // EMRI register access (word offset -> AXI address in the window)
  task automatic host_wr(input logic [15:0] word, input logic [31:0] d);
      begin
          axi_wr(EMRI_BASE + ({16'h0, word} << 2), d);
      end
  endtask

  task automatic host_rd(input logic [15:0] word, output logic [31:0] d);
      begin
          axi_rd(EMRI_BASE + ({16'h0, word} << 2), d);
      end
  endtask

  // Poll EFP_STATUS until busy=0 (spec §3.2: host MUST wait busy=0 before the
  // next EFP_CMD write).
  task automatic host_wait_idle;
      logic [31:0] s;
      integer to;
      begin
          to = 0;
          host_rd(R_EFP_STATUS, s);
          while (s[4] && to < 100000) begin
              host_rd(R_EFP_STATUS, s);
              to = to + 1;
          end
          chk(!s[4], "EFP_STATUS.busy cleared (host may issue next command)");
      end
  endtask

  // ---- image staging (spec §3.2 step 1) ---------------------------------------
  localparam int SEL_A        = 0;   // image A, valid signature
  localparam int SEL_B        = 1;   // image B, valid signature
  localparam int SEL_A_TAMPER = 2;   // image A, tampered signature

  task automatic host_stage(input integer sel, input logic [31:0] words,
                            input logic [31:0] region);
      integer k;
      begin
          for (k = 0; k < 8; k = k + 1)
              host_wr(R_IMG_DIGEST + 16'(k),
                      (sel == SEL_B) ? DAEMON_IMG_B_DIGEST[k]
                                     : DAEMON_IMG_A_DIGEST[k]);
          for (k = 0; k < 16; k = k + 1)
              host_wr(R_IMG_SIG + 16'(k),
                      (sel == SEL_B)        ? DAEMON_IMG_B_SIG[k]        :
                      (sel == SEL_A_TAMPER) ? DAEMON_IMG_A_SIG_TAMPER[k] :
                                              DAEMON_IMG_A_SIG[k]);
          host_wr(R_EFP_IMG_WORDS, words);
          host_wr(R_EFP_REGION, region);
      end
  endtask

  // Stream the frame words through OCC_WDATA (spec §3.2 step 5: the host
  // streams while the daemon supervises OCC_STATUS in LOAD).
  task automatic host_stream(input integer sel);
      integer k;
      begin
          if (sel == SEL_B) begin
              for (k = 0; k < DAEMON_IMG_B_NWORDS; k = k + 1)
                  host_wr(R_OCC_WDATA, DAEMON_IMG_B_WORDS[k]);
          end else begin
              for (k = 0; k < DAEMON_IMG_A_NWORDS; k = k + 1)
                  host_wr(R_OCC_WDATA, DAEMON_IMG_A_WORDS[k]);
          end
      end
  endtask

  // ---- fabric observation (the REAL fabric outputs) ----------------------------
  task automatic observe_toggle(input logic [511:0] tag);
      integer k;
      logic s0, s1;
      begin
          s0 = 1'b0; s1 = 1'b0;
          for (k = 0; k < 128; k = k + 1) begin
              @(posedge clk);
              if (clb_out_obs[0] === 1'b0) s0 = 1'b1;
              if (clb_out_obs[0] === 1'b1) s1 = 1'b1;
          end
          chk(s0 && s1, tag);
      end
  endtask

  task automatic observe_const(input logic v, input logic [511:0] tag);
      integer k;
      logic bad;
      begin
          bad = 1'b0;
          for (k = 0; k < 128; k = k + 1) begin
              @(posedge clk);
              if (clb_out_obs[0] !== v) bad = 1'b1;
          end
          chk(!bad, tag);
      end
  endtask

  // ============================================================================
  // Test sequence (spec §3.2 EFP flows)
  // ============================================================================
  logic [31:0] rd;
  logic [31:0] cap_shadow;   // region-1 RAM shadow snapshot for the §3.7 refusal check

  initial begin : main_seq
      // idle the host BFM + UART RX
      h_awvalid = 1'b0; h_awaddr = 32'h0;
      h_wvalid  = 1'b0; h_wdata  = 32'h0;
      h_bready  = 1'b0;
      h_arvalid = 1'b0; h_araddr = 32'h0;
      h_rready  = 1'b0;
      uart0_rxd = 1'b1;

      rst_n = 1'b0;
      repeat (20) @(posedge clk);
      rst_n = 1'b1;

      // ---- 0. boot: banner + Ed25519 selftest + EMRI probe + daemon up --------
      $display("[0] boot (selftest = 2 verifies, ~1.7 s sim)");
      expect_uart("bmc-fw v0.2 daemon boot\n", "boot banner");
      expect_uart("ed25519 selftest OK\n", "boot Ed25519 selftest");
      expect_uart("EMRI MAGIC=45544852 CAP=00000001\n", "EMRI MAGIC/CAP probe");
      // E1-IO1 (2026-09-02): main.c inits the EFP-SPI front-end after the
      // EMRI probe and before daemon_init — exact-match the new boot line so
      // the expect_uart cursor stays aligned.
      expect_uart("efp-spi ready\n", "EFP-SPI front-end initialized");
      expect_uart("daemon ready\n", "daemon poll loop entered");

      // ---- 1. run image A (TFF), auto-alloc ---------------------------------
      $display("[1] run image A (TFF) — EFP_REGION=0xFF auto-alloc");
      host_stage(SEL_A, 32'd12, 32'h0000_00FF);
      host_wr(R_EFP_CMD, {24'h0, EFP_CMD_RUN});
      expect_uart("cmd run\nst VERIFY\n", "run A: accepted + VERIFY");
      expect_uart("verify ok\nst ALLOC\nalloc r0\nst BLANK\nblank ok\nst LOAD\n",
                  "run A: VERIFY ok -> ALLOC r0 -> BLANK -> LOAD");
      host_stream(SEL_A);
      expect_uart("load ok\nst READBACK\nreadback ok\nst RUNNING r0 done\n",
                  "run A: LOAD -> READBACK -> RUNNING");
      host_wait_idle();
      host_rd(R_EFP_STATUS, rd);
      chk(rd[3:0] == EFP_S_RUNNING && rd[5] == 1'b1,
          "EFP_STATUS = RUNNING + done");
      observe_toggle("run A: clb_out_obs[0] toggles (TFF on real fabric)");
      // ---- 1a. v0.6 §3.8: completed deploy notified the HW monitor ----------
      $display("[1a] MON_RECFG_COUNT after run A (region-0 deploy count)");
      host_rd(R_MON_RECFG_COUNT, rd);
      chk(rd[15:0] == 32'd1, "MON_RECFG_COUNT.region0 == 1 after one deploy");

      // ---- 1b. v0.6 §3.7 capability gate: over-declared IO -> err 11 --------
      $display("[1b] run with CAP_DECL_IO=0xFFFFFFFF (auto-alloc region 1)");
      host_stage(SEL_A, 32'd12, 32'h0000_00FF);
      cap_shadow = u_cfgram.mem[16'h1000];   // region-1 window, untouched so far
      host_wr(R_CAP_DECL_IO, 32'hFFFF_FFFF);
      host_wr(R_EFP_CMD, {24'h0, EFP_CMD_RUN});
      expect_uart("cmd run\nst VERIFY\n", "cap: accepted + VERIFY");
      expect_uart("verify ok\nst ALLOC\nalloc r1\n",
                  "cap: VERIFY ok -> ALLOC r1 (auto)");
      expect_uart("err capability_denied\nst ERROR\n",
                  "cap: EFP_ERR=capability_denied, ERROR (no BLANK)");
      host_wait_idle();
      host_rd(R_EFP_ERR, rd);
      chk(rd[7:0] == EFP_ERR_CAPABILITY_DENIED, "EFP_ERR = capability_denied (11)");
      host_rd(R_EFP_STATUS, rd);
      chk(rd[3:0] == EFP_S_ERROR, "cap: EFP_STATUS = ERROR");
      host_rd(R_CAP_STATUS, rd);
      chk(rd[1] == 1'b1, "cap: CAP_STATUS.denied[1] set by the HW comparator");
      observe_toggle("cap deny: fabric untouched (image A still toggling)");
      chk(u_cfgram.mem[16'h1000] === cap_shadow,
          "cap deny: region-1 RAM shadow unchanged (no BLANK/mutation)");
      host_wr(R_CAP_DECL_IO, 32'h0000_0000);   // release the declaration
      host_rd(R_CAP_STATUS, rd);
      chk(rd[1] == 1'b0, "cap: CAP_STATUS.denied clears when undeclared");

      // ---- 1c. v0.7 §3.9: BMC-driven context save/restore (E2-FAB3b) ----------
      // Region 0 is RUNNING with image A (TFF). Pause it, prove the fabric is
      // frozen for the whole PAUSED period, then restore and prove it resumes.
      $display("[1c] context save/restore — pause freezes, restore resumes");
      host_wr(R_EFP_REGION, 32'h0000_0000);
      host_wr(R_EFP_CMD, {24'h0, EFP_CMD_CTX_SAVE});
      expect_uart("cmd ctx_save\n", "ctx_save: command dispatched");
      expect_uart("st CTXSAVE r0\n", "ctx_save: daemon entered the context path");
      expect_uart("st PAUSED r0\n", "ctx_save: region 0 PAUSED");
      host_wait_idle();
      host_rd(R_EFP_STATUS, rd);
      chk(rd[3:0] == EFP_S_PAUSED, "ctx_save: EFP_STATUS = PAUSED (9)");
      host_rd(R_EFP_ERR, rd);
      chk(rd[7:0] == EFP_ERR_NONE, "ctx_save: no error");
      // Frozen for the whole PAUSED period (spec §3.9 step 2).
      ctx_ref        = clb_out_obs[0];
      ctx_frozen_bad = 1'b0;
      for (ctx_k = 0; ctx_k < 512; ctx_k = ctx_k + 1) begin
          @(negedge clk);
          if (clb_out_obs[0] !== ctx_ref) ctx_frozen_bad = 1'b1;
      end
      chk(!ctx_frozen_bad, "ctx_save: fabric frozen for 512 cycles while PAUSED");
      // Restore: unfreeze + resume.
      host_wr(R_EFP_CMD, {24'h0, EFP_CMD_CTX_RESTORE});
      expect_uart("cmd ctx_restore\n", "ctx_restore: command dispatched");
      expect_uart("st CTXRESTORE r0\n", "ctx_restore: daemon entered the context path");
      expect_uart("st RESUMED r0\n", "ctx_restore: region 0 resumed");
      host_wait_idle();
      host_rd(R_EFP_STATUS, rd);
      chk(rd[3:0] == EFP_S_RUNNING, "ctx_restore: EFP_STATUS = RUNNING (6)");
      host_rd(R_EFP_ERR, rd);
      chk(rd[7:0] == EFP_ERR_NONE, "ctx_restore: no error");
      observe_toggle("ctx_restore: clb_out_obs[0] toggling again after resume");
      // Negative: restore while RUNNING -> ctx_error, no state change.
      host_wr(R_EFP_CMD, {24'h0, EFP_CMD_CTX_RESTORE});
      expect_uart("cmd ctx_restore\nerr ctx_error\nst ERROR\n",
                  "ctx negative: restore while RUNNING refused (13)");
      host_wait_idle();
      host_rd(R_EFP_ERR, rd);
      chk(rd[7:0] == EFP_ERR_CTX_ERROR,
          "ctx negative: restore while RUNNING -> ctx_error (13)");
      host_rd(R_EFP_STATUS, rd);
      chk(rd[3:0] == EFP_S_ERROR, "ctx negative: EFP_STATUS = ERROR");
      observe_toggle("ctx negative: fabric still running (no state change)");
      // Negative: save on a FREE region (region 1) -> ctx_error.
      host_wr(R_EFP_REGION, 32'h0000_0001);
      host_wr(R_EFP_CMD, {24'h0, EFP_CMD_CTX_SAVE});
      expect_uart("cmd ctx_save\nerr ctx_error\nst ERROR\n",
                  "ctx negative: save on FREE region refused (13)");
      host_wait_idle();
      host_rd(R_EFP_ERR, rd);
      chk(rd[7:0] == EFP_ERR_CTX_ERROR,
          "ctx negative: save on FREE region -> ctx_error (13)");
      host_wr(R_EFP_REGION, 32'h0000_0000);   // restore the region selector

      // ---- 1d. v0.8 §3.10: region lock matrix (E2-SEC1b) ---------------------
      // The running region is write-protected in hardware; a raw OCC WRITE from
      // any bus master is refused with done_code LOCKED and touches no config.
      $display("[1d] region lock matrix — running region is write-protected");
      host_rd(R_LKM_STATUS, rd);
      chk(rd[0] == 1'b1, "lock: region 0 auto-locked while RUNNING");
      lkm_shadow = u_cfgram.mem[16'h0000];   // region-0 frame word 0 (image A)
      host_wr(R_OCC_FRAME_ADDR, 32'h0000_0000);
      host_wr(R_OCC_WORD_COUNT, 32'd1);
      host_wr(R_OCC_CMD, 32'h0000_0101);     // start | region0 | WRITE
      lkm_to = 0;
      host_rd(R_OCC_STATUS, rd);
      while ((rd[3] == 1'b0) && (lkm_to < 4000)) begin
          host_rd(R_OCC_STATUS, rd);
          lkm_to = lkm_to + 1;
      end
      chk(rd[3] == 1'b1, "lock: raw WRITE completed (done_flag)");
      chk(rd[5:4] == 2'd3, "lock: raw WRITE refused with done_code LOCKED (3)");
      chk(u_cfgram.mem[16'h0000] === lkm_shadow,
          "lock: config RAM unchanged by the refused raw write");
      // Global lock gates the same way, and clearing it restores LKM_STATUS.
      host_wr(R_LKM_CMD, 32'h0000_0003);     // op 3 = lock all
      host_rd(R_LKM_STATUS, rd);
      chk(rd[8] == 1'b1, "lock: global lock set (LKM_STATUS[8])");
      host_wr(R_LKM_CMD, 32'h0000_0004);     // op 4 = clear global ONLY (§3.10)
      host_rd(R_LKM_STATUS, rd);
      chk(rd[8] == 1'b0, "lock: global unlock clears the global bit");
      chk(rd[0] == 1'b1, "lock: global unlock leaves region 0 locked (§3.10)");
      host_wr(R_LKM_CMD, 32'h0000_0022);     // op 2, region 0 = explicit unlock
      host_rd(R_LKM_STATUS, rd);
      chk(rd[8:0] == 9'h0, "lock: explicit region unlock clears LKM_STATUS");

      // ---- 2. restart (stop + re-run last staged metadata) -------------------
      // Also the "subsequent good deploy" after the §3.7 refusal: a full
      // VERIFY->ALLOC->BLANK->LOAD->READBACK->RUNNING completes, so the
      // capability denial left no stuck state.
      $display("[2] restart (re-verify + reload of image A)");
      host_wr(R_EFP_CMD, {24'h0, EFP_CMD_RESTART});
      expect_uart("cmd restart\nst BLANK\nblank ok\nst VERIFY\n",
                  "restart: stop-part BLANK + VERIFY");
      expect_uart("verify ok\nst ALLOC\nalloc r0\nst BLANK\nblank ok\nst LOAD\n",
                  "restart: VERIFY ok -> ALLOC -> BLANK -> LOAD");
      host_stream(SEL_A);
      expect_uart("load ok\nst READBACK\nreadback ok\nst RUNNING r0 done\n",
                  "restart: RUNNING again");
      host_wait_idle();
      observe_toggle("restart: clb_out_obs[0] toggles again");
      host_rd(R_EFP_ERR, rd);
      chk(rd[7:0] == EFP_ERR_NONE,
          "recovery: EFP_ERR none after the cap refusal (no stuck state)");

      // ---- 3. stop region 0 ---------------------------------------------------
      $display("[3] stop region 0");
      host_wr(R_EFP_REGION, 32'h0000_0000);
      host_wr(R_EFP_CMD, {24'h0, EFP_CMD_STOP});
      expect_uart("cmd stop\nst BLANK\nblank ok\nst STOPPED r0\n",
                  "stop: BLANK -> STOPPED");
      host_wait_idle();
      host_rd(R_EFP_STATUS, rd);
      chk(rd[3:0] == EFP_S_STOPPED, "EFP_STATUS = STOPPED");
      observe_const(1'b0, "stopped: clb_out_obs[0] constant 0 (region blanked)");

      // ---- 4. run image B (const1), auto-alloc --------------------------------
      $display("[4] run image B (const1) — auto-alloc first free");
      host_stage(SEL_B, 32'd1, 32'h0000_00FF);
      host_wr(R_EFP_CMD, {24'h0, EFP_CMD_RUN});
      expect_uart("cmd run\nst VERIFY\n", "run B: accepted + VERIFY");
      expect_uart("verify ok\nst ALLOC\nalloc r0\nst BLANK\nblank ok\nst LOAD\n",
                  "run B: VERIFY ok -> ALLOC r0 -> BLANK -> LOAD");
      host_stream(SEL_B);
      expect_uart("load ok\nst READBACK\nreadback ok\nst RUNNING r0 done\n",
                  "run B: RUNNING");
      host_wait_idle();
      observe_const(1'b1, "run B: clb_out_obs[0] constant 1");

      // ---- 5. negative: tampered signature -> bad_sig, fabric untouched -------
      $display("[5] run with TAMPERED signature (image A metadata)");
      host_stage(SEL_A_TAMPER, 32'd12, 32'h0000_00FF);
      host_wr(R_EFP_CMD, {24'h0, EFP_CMD_RUN});
      expect_uart("cmd run\nst VERIFY\n", "tamper: accepted + VERIFY");
      expect_uart("err bad_sig\nst ERROR\n", "tamper: EFP_ERR=bad_sig, ERROR");
      host_wait_idle();
      host_rd(R_EFP_ERR, rd);
      chk(rd[7:0] == EFP_ERR_BAD_SIG, "EFP_ERR = bad_sig (1)");
      host_rd(R_EFP_STATUS, rd);
      chk(rd[3:0] == EFP_S_ERROR, "EFP_STATUS = ERROR");
      observe_const(1'b1, "tamper: fabric untouched (B still constant 1)");

      // ---- 6. negative: run on RUNNING region -> region_full ------------------
      $display("[6] run on RUNNING region 0 (explicit)");
      host_stage(SEL_B, 32'd1, 32'h0000_0000);
      host_wr(R_EFP_CMD, {24'h0, EFP_CMD_RUN});
      expect_uart(
          "cmd run\nst VERIFY\nverify ok\nst ALLOC\nerr region_full\nst ERROR\n",
          "conflict: verify ok, ALLOC -> region_full");
      host_wait_idle();
      host_rd(R_EFP_ERR, rd);
      chk(rd[7:0] == EFP_ERR_REGION_FULL, "EFP_ERR = region_full (2)");
      observe_const(1'b1, "conflict: fabric still B (constant 1)");

      // ---- 7. abort -> IDLE, region blanked ------------------------------------
      $display("[7] abort");
      host_wr(R_EFP_CMD, {24'h0, EFP_CMD_ABORT});
      expect_uart("cmd abort\nst BLANK\nblank ok\nst IDLE\n",
                  "abort: best-effort BLANK -> IDLE");
      host_wait_idle();
      host_rd(R_EFP_STATUS, rd);
      chk(rd[3:0] == EFP_S_IDLE, "EFP_STATUS = IDLE after abort");
      observe_const(1'b0, "abort: clb_out_obs[0] constant 0 (blanked)");
      // ---- 8. v0.6 §3.8 anomaly monitor: forced reconfig spike -> throttle --
      $display("[8] anomaly monitor: reconfig spike throttles region 0");
      host_wr(R_MON_ANOM_WINDOW, 32'd1);           // 1 tick (~4096 clk) window
      host_wr(R_MON_ANOM_THRESH, 32'h0000_0000);  // any delta > 0 spikes
      repeat (5000) @(posedge clk);               // let the window snapshot settle
      host_wr(R_MON_ANOM_STATUS, 32'hFFFF_FFFF);  // W1C: drop stale spike flags
      host_wr(R_MON_NOTIFY, 32'h0000_0001);       // one completed-deploy pulse, r0
      repeat (5000) @(posedge clk);               // cross the next monitor tick
      host_rd(R_MON_ANOM_STATUS, rd);
      chk(rd[0] == 1'b1, "anomaly: MON_ANOM_STATUS throttle[0] set");
      chk(rd[8] == 1'b1, "anomaly: MON_ANOM_STATUS flag[8] (recfg spike r0) set");
      host_rd(R_MON_RECFG_COUNT, rd);
      chk(rd[15:0] == 32'd4,
          "anomaly: MON_RECFG_COUNT.region0 == 4 (3 deploys + host notify)");
      host_rd(R_CAP_STATUS, rd);
      chk(rd[2] == 1'b1, "anomaly: CAP_STATUS.throttled[2] set");
      // A deploy to the throttled region is refused with no ALLOC at all.
      host_stage(SEL_B, 32'd1, 32'h0000_0000);
      host_wr(R_EFP_CMD, {24'h0, EFP_CMD_RUN});
      expect_uart("cmd run\nst VERIFY\n", "throttle: accepted + VERIFY");
      expect_uart("verify ok\nerr rate_limited\nst ERROR\n",
                  "throttle: EFP_ERR=rate_limited, ERROR (no ALLOC)");
      host_wait_idle();
      host_rd(R_EFP_ERR, rd);
      chk(rd[7:0] == EFP_ERR_RATE_LIMITED, "EFP_ERR = rate_limited (12)");
      host_rd(R_EFP_STATUS, rd);
      chk(rd[3:0] == EFP_S_ERROR, "throttle: EFP_STATUS = ERROR");
      observe_const(1'b0, "throttle: region 0 fabric untouched (stays blanked)");

      // ---- report ---------------------------------------------------------------
      if (errors == 0)
          $display("TEST PASSED: E1-RUN2 daemon — EFP run/restart/stop/abort on real fabric, bad_sig + region_full rejected, v0.6 cap-gate (11) + anomaly throttle (12) enforced, MON_RECFG_COUNT notified, v0.7 ctx pause/resume (frozen while PAUSED, resumed after restore, ctx_error refusals), UART log exact-matched");
      else
          $display("TEST FAILED: %0d errors", errors);
      $finish;
  end

  // -- Watchdog -------------------------------------------------------------------
  initial begin
      // Total sim ≈ 10 verify-equivalents × ~0.84 s + deploys ≈ ~9 s sim.
      repeat (25) #(1000000000);   // 25 s hard cap
      $display("TEST FAILED: watchdog timeout (rxn=%0d rxr=%0d errors=%0d)",
               rxn, rxr, errors);
      $finish;
  end

